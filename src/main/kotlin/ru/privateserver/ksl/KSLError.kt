    val code: String get() = String.format("%04d%c", number, category.letter)

    // Prefix for log lines.
    val tag: String get() = "[$code]"

    companion object {
        private val byCode: Map<String, KSLError> by lazy { entries.associateBy { it.code } }

        // Accepts 0583c, #0583c and [0583c], in any letter case.
        fun find(code: String): KSLError? =
            byCode[code.trim().removePrefix("#").removePrefix("[").removeSuffix("]").lowercase()]

        val categories: List<KSLErrorCategory> get() = KSLErrorCategory.entries
    }
