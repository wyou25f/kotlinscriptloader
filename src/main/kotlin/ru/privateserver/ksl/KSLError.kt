package ru.privateserver.ksl

// Every error and warning KSL prints carries a code like 0583c: four digits and a category letter.
// The numbers are deliberately scattered (not 0001, 0002, ...) so a code is easy to recognise and search for;
// the letter is the category. /ksl error <code> explains a code; docs/Error-Codes.md lists all of them.
enum class KSLErrorCategory(val letter: Char, val title: String) {
    SCRIPT('a', "Загрузка и выполнение скриптов"),
    DATABASE('b', "База данных и хранилище"),
    COMMAND('c', "Команды и события"),
    EFFECT('d', "Эффекты и частицы"),
    ENTITY('e', "Мобы и сущности"),
    GUI('f', "GUI-меню"),
    INTEGRATION('g', "Интеграции, хуки и Discord"),
    ADDON('h', "Аддоны и API"),
    CONFIG('i', "Конфигурация и файлы"),
    TASK('j', "Планировщик и задачи"),
    PLACEHOLDER('k', "Плейсхолдеры и тексты"),
    SYSTEM('l', "Система и остановка плагина");

    companion object {
        fun byLetter(letter: Char): KSLErrorCategory? = entries.firstOrNull { it.letter == letter.lowercaseChar() }
    }
}

